-- NEXORA · Esquema inicial (perfil comprador del MVP)
-- Cada tabla guarda los identificadores de sus relaciones como columnas simples (sin cascadas implícitas).

CREATE TABLE zona (
    id          VARCHAR(40)  PRIMARY KEY,
    distrito    VARCHAR(80)  NOT NULL,
    nombre      VARCHAR(120) NOT NULL
);

CREATE TABLE usuario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(160) NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    rol            VARCHAR(20)  NOT NULL,          -- COMPRADOR, PROVEEDOR, ADMIN
    estado         VARCHAR(20)  NOT NULL,          -- ACTIVO, SUSPENDIDO
    creado_en      TIMESTAMP    NOT NULL
);

CREATE TABLE sesion (
    token       VARCHAR(80) PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    expira_en   TIMESTAMP   NOT NULL
);

CREATE TABLE negocio (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT       REFERENCES usuario(id) ON DELETE CASCADE,  -- NULL en las bodegas simuladas de la demo
    nombre       VARCHAR(120) NOT NULL,
    responsable  VARCHAR(120) NOT NULL,
    celular      VARCHAR(20)  NOT NULL,
    distrito     VARCHAR(80)  NOT NULL,
    zona_id      VARCHAR(40)  NOT NULL REFERENCES zona(id),
    direccion    VARCHAR(200) NOT NULL,
    ruc          VARCHAR(11),
    descripcion  VARCHAR(300),
    horario      VARCHAR(120)
);

CREATE TABLE proveedor (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social       VARCHAR(160) NOT NULL,
    ruc                VARCHAR(11)  NOT NULL,
    estado             VARCHAR(20)  NOT NULL,      -- APROBADO, EN_REVISION, SUSPENDIDO
    entregas_a_tiempo  INTEGER      NOT NULL DEFAULT 0,
    entregas_total     INTEGER      NOT NULL DEFAULT 0
);

CREATE TABLE categoria (
    id      VARCHAR(40)  PRIMARY KEY,
    nombre  VARCHAR(80)  NOT NULL
);

CREATE TABLE producto (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id      BIGINT        NOT NULL REFERENCES proveedor(id),
    categoria_id      VARCHAR(40)   NOT NULL REFERENCES categoria(id),
    nombre            VARCHAR(120)  NOT NULL,
    marca             VARCHAR(80)   NOT NULL,
    presentacion      VARCHAR(80)   NOT NULL,
    unidad            VARCHAR(30)   NOT NULL,      -- unidad equivalente en plural: botellas, kg, latas...
    unidad_venta      VARCHAR(60)   NOT NULL,      -- caja de 12, saco de 50 kg...
    equivalencia      INTEGER       NOT NULL,      -- unidades equivalentes por unidad de venta
    palabras_clave    VARCHAR(200)  NOT NULL,      -- sinónimos para interpretar pedidos
    minimo            INTEGER       NOT NULL,      -- unidades para que exista la compra conjunta
    plazo_entrega     INTEGER       NOT NULL,      -- días entre el cierre y la entrega
    zonas             VARCHAR(200)  NOT NULL,      -- ids de zona separados por coma
    imagen            VARCHAR(120),
    activo            BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE tramo_precio (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id  BIGINT        NOT NULL REFERENCES producto(id) ON DELETE CASCADE,
    desde        INTEGER       NOT NULL,
    hasta        INTEGER,                          -- NULL = sin límite
    precio       NUMERIC(10,2) NOT NULL
);

CREATE TABLE compra_conjunta (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id        BIGINT        NOT NULL REFERENCES producto(id),
    proveedor_id       BIGINT        NOT NULL REFERENCES proveedor(id),
    zona_id            VARCHAR(40)   NOT NULL REFERENCES zona(id),
    estado             VARCHAR(30)   NOT NULL,     -- PROPUESTA, BUSCANDO_PARTICIPANTES, EN_COTIZACION, PRECIO_POR_ACEPTAR, CONFIRMADA, CANCELADA, VENCIDA
    estado_desde       TIMESTAMP     NOT NULL,
    fecha_cierre       DATE          NOT NULL,
    entrega_desde      DATE          NOT NULL,
    entrega_hasta      DATE          NOT NULL,     -- el último día es el que cuenta para llegar a tiempo
    precio_final       NUMERIC(10,2),
    costo_transporte   NUMERIC(10,2),              -- por negocio; NULL = aún no se conoce
    compensacion       VARCHAR(160),               -- compromiso del proveedor si se retrasa
    entrega_estado     VARCHAR(20),                -- EN_PREPARACION, EN_CAMINO, ENTREGADA, RETRASADA
    creada_en          TIMESTAMP     NOT NULL
);

CREATE TABLE necesidad (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id           BIGINT        NOT NULL REFERENCES negocio(id) ON DELETE CASCADE,
    producto_id          BIGINT        NOT NULL REFERENCES producto(id),
    texto_original       VARCHAR(300),
    cantidad             INTEGER       NOT NULL,
    marca_preferida      VARCHAR(80),
    acepta_equivalente   BOOLEAN       NOT NULL DEFAULT TRUE,
    precio_actual        NUMERIC(10,2),            -- lo que paga hoy comprando solo (opcional)
    fecha_requerida      DATE          NOT NULL,
    estado               VARCHAR(20)   NOT NULL,   -- ACTIVA, EN_COMPRA, ATENDIDA, CANCELADA
    creada_en            TIMESTAMP     NOT NULL
);

CREATE TABLE participacion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id         BIGINT        NOT NULL REFERENCES compra_conjunta(id) ON DELETE CASCADE,
    negocio_id        BIGINT        NOT NULL REFERENCES negocio(id) ON DELETE CASCADE,
    necesidad_id      BIGINT        REFERENCES necesidad(id) ON DELETE SET NULL,
    cantidad          INTEGER       NOT NULL,
    estado            VARCHAR(20)   NOT NULL,      -- ACTIVA, RETIRADA
    precio_estimado   NUMERIC(10,2) NOT NULL,      -- precio del tramo cuando se unió
    precio_aceptado   BOOLEAN       NOT NULL DEFAULT FALSE,
    recibido          BOOLEAN       NOT NULL DEFAULT FALSE,
    creada_en         TIMESTAMP     NOT NULL
);

CREATE TABLE aviso (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id  BIGINT        NOT NULL REFERENCES compra_conjunta(id) ON DELETE CASCADE,
    texto      VARCHAR(300)  NOT NULL,
    creado_en  TIMESTAMP     NOT NULL
);

CREATE TABLE notificacion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT        NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    tipo        VARCHAR(30)   NOT NULL,
    texto       VARCHAR(300)  NOT NULL,
    enlace      VARCHAR(160),
    leida       BOOLEAN       NOT NULL DEFAULT FALSE,
    creada_en   TIMESTAMP     NOT NULL
);

CREATE TABLE incidencia (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id    BIGINT        NOT NULL REFERENCES compra_conjunta(id) ON DELETE CASCADE,
    negocio_id   BIGINT        NOT NULL REFERENCES negocio(id) ON DELETE CASCADE,
    motivo       VARCHAR(30)   NOT NULL,           -- NO_LLEGO, INCOMPLETO, DANADO, TARDE, PRECIO_DISTINTO
    descripcion  VARCHAR(500)  NOT NULL,
    estado       VARCHAR(20)   NOT NULL,           -- ABIERTA, EN_REVISION, RESUELTA
    respuesta    VARCHAR(500),
    creada_en    TIMESTAMP     NOT NULL
);

CREATE INDEX ix_negocio_usuario     ON negocio(usuario_id);
CREATE INDEX ix_necesidad_negocio   ON necesidad(negocio_id);
CREATE INDEX ix_participacion_compra ON participacion(compra_id);
CREATE INDEX ix_participacion_negocio ON participacion(negocio_id);
CREATE INDEX ix_compra_zona_producto ON compra_conjunta(zona_id, producto_id);
CREATE INDEX ix_notificacion_usuario ON notificacion(usuario_id, leida);
