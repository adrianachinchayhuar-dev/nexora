-- Comunicación vinculada a cada compra conjunta y compras ocultas («No me interesa»).

-- Preguntas públicas y anónimas: todas las bodegas de la compra ven la pregunta y la respuesta,
-- pero nadie ve quién preguntó.
CREATE TABLE pregunta (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id      BIGINT        NOT NULL REFERENCES compra_conjunta(id) ON DELETE CASCADE,
    negocio_id     BIGINT        NOT NULL REFERENCES negocio(id) ON DELETE CASCADE,
    texto          VARCHAR(300)  NOT NULL,
    respuesta      VARCHAR(500),
    creada_en      TIMESTAMP     NOT NULL,
    respondida_en  TIMESTAMP
);

-- Chat privado entre un negocio y el proveedor de la compra.
CREATE TABLE mensaje (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id   BIGINT        NOT NULL REFERENCES compra_conjunta(id) ON DELETE CASCADE,
    negocio_id  BIGINT        NOT NULL REFERENCES negocio(id) ON DELETE CASCADE,
    autor       VARCHAR(20)   NOT NULL,     -- NEGOCIO o PROVEEDOR
    texto       VARCHAR(500)  NOT NULL,
    leido       BOOLEAN       NOT NULL DEFAULT FALSE,
    creado_en   TIMESTAMP     NOT NULL
);
CREATE INDEX idx_mensaje_conversacion ON mensaje (compra_id, negocio_id, creado_en);

CREATE TABLE compra_oculta (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT NOT NULL REFERENCES negocio(id) ON DELETE CASCADE,
    compra_id   BIGINT NOT NULL REFERENCES compra_conjunta(id) ON DELETE CASCADE,
    UNIQUE (negocio_id, compra_id)
);
